function englishTitleFor(video: FarsiSourceVideo): string {
  const verifiedTranslation = ENGLISH_TITLE_BY_VIDEO_ID[video.youtubeId];
  if (verifiedTranslation) return verifiedTranslation;

  return video.sourceTitle
    .split(/\s*[/|]?\s*ترجمه/u)[0]
    .replace(/\s+/g, ' ')
    .trim();
}

